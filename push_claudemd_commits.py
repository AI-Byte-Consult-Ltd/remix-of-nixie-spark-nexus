def run(cmd):
    print("+", " ".join(cmd))
    subprocess.run(cmd, check=True)


def main():
    if subprocess.run(["git", "status", "--porcelain"],
                      capture_output=True, text=True, check=True).stdout.strip():
        print("Рабочее дерево не чистое — сначала закоммить или застэшь изменения.")
        sys.exit(1)

    branch = subprocess.run(["git", "branch", "--show-current"],
                            capture_output=True, text=True, check=True).stdout.strip()
    if branch != BRANCH:
        print(f"Сейчас на ветке {branch!r}, а нужна {BRANCH!r}.")
        print(f"Переключись: git checkout {BRANCH}")
        sys.exit(1)

    with tempfile.NamedTemporaryFile(suffix=".patch", delete=False) as tmp:
        tmp.write(base64.b64decode(PATCH_B64))
        patch_file = tmp.name
    try:
        run(["git", "am", patch_file])
        run(["git", "push", "-u", "origin", BRANCH])
        print("\nГотово: три коммита применены и запушены.")
    finally:
        os.unlink(patch_file)


if __name__ == "__main__":
    main()
